#!/usr/bin/env python3
"""Write sanitized snapshots of the live Hermes and OpenClaw agent configuration into agents/.

Whitelist-based: only fields listed here are copied, so an unexpected value (a token, a key, an
account identifier) can never leak. Home-directory paths are rewritten to `~`. The script then
scans its own output and refuses to finish if anything secret-like or machine-specific remains.

Not copied, by design: Hermes `.env` / `auth.json`, OpenClaw's gateway token file, API keys, GitHub
tokens, session databases.

Usage: python3 scripts/snapshot_agent_configs.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HOME = str(Path.home())
OPENCLAW_CONFIG = Path.home() / ".openclaw-confer-newsroom" / "openclaw.json"
HERMES_PROFILES = Path.home() / ".hermes" / "profiles"
SECRETISH = re.compile(
    r"(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_|sk-[A-Za-z0-9]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY|AKIA[0-9A-Z]{16}"
    r"|ocid1\.[a-z]+\.oc1\.[a-z0-9-]*\.[a-z0-9]{10,}|Bearer [A-Za-z0-9._-]{12,}|/Users/[A-Za-z0-9._-]+)"
)


def tilde(value):
    if isinstance(value, str):
        return value.replace(HOME, "~")
    if isinstance(value, list):
        return [tilde(v) for v in value]
    if isinstance(value, dict):
        return {k: tilde(v) for k, v in value.items()}
    return value


def pick(src: dict, keys: list[str]) -> dict:
    return {k: src[k] for k in keys if k in src}


def hermes_snapshot(profile: str) -> str:
    cfg = (HERMES_PROFILES / profile / "config.yaml").read_text()
    prof = (HERMES_PROFILES / profile / "profile.yaml").read_text()
    return (
        f"# Sanitized snapshot of the live Hermes profile `{profile}` (see agents/SNAPSHOT.md).\n"
        "# Generated by scripts/snapshot_agent_configs.py. Not included: .env, auth.json, sessions, memories.\n"
        "# Execution settings are passed per run by the orchestrator, not stored here:\n"
        f"#   hermes -p {profile} -z <prompt> -t todo --usage-file <report.json>   (toolset `todo` only)\n"
        "# The profile was created with --no-skills; no custom skills exist.\n"
        "---\n# config.yaml (verbatim)\n" + cfg.rstrip() + "\n---\n# profile.yaml (verbatim)\n" + prof.rstrip() + "\n"
    )


def openclaw_snapshot() -> dict:
    c = json.loads(OPENCLAW_CONFIG.read_text())
    agents = c.get("agents", {})
    entries = {}
    for name, e in agents.get("entries", {}).items():
        entries[name] = pick(e, ["name", "description", "workspace", "model", "sandbox", "tools", "identity"])
    models = {}
    for pname, p in (c.get("models", {}).get("providers", {}) or {}).items():
        models[pname] = {
            **pick(p, ["baseUrl", "api"]),
            "apiKey": "<placeholder: the local Ollama provider takes no key; cloud keys come from the environment>",
            "models": [pick(m, ["id", "name", "contextWindow", "maxTokens", "reasoning", "input"]) for m in p.get("models", [])],
        }
    snap = {
        "_note": "Sanitized snapshot of the live OpenClaw profile `confer-newsroom` (OpenClaw 2026.10.1). "
                 "Generated by scripts/snapshot_agent_configs.py; see agents/SNAPSHOT.md.",
        "gateway": {
            **pick(c.get("gateway", {}), ["mode", "bind"]),
            "auth": {"mode": c.get("gateway", {}).get("auth", {}).get("mode"),
                     "token": "<stored in a separate mode-600 file; not included>"},
        },
        "tools": c.get("tools"),
        "browser": c.get("browser"),
        "agents": {"defaults": agents.get("defaults"), "ownership": agents.get("ownership"), "entries": entries},
        "models": {"providers": models},
        "model_provider_for_cloud_models": "ollama-cloud (built in; OLLAMA_API_KEY is read from the gateway's environment)",
        "plugins": c.get("plugins"),
        "skills": "none written; OpenClaw's bundled plugin skills (e.g. browser-automation) are unused because the browser is disabled",
    }
    return tilde(snap)


def main() -> int:
    outputs: dict[Path, str] = {}
    for profile in ("dispatch", "reviewer"):
        outputs[REPO / "agents" / "hermes" / profile / "config.snapshot.yaml"] = hermes_snapshot(profile)
    outputs[REPO / "agents" / "openclaw" / "openclaw.snapshot.json"] = json.dumps(openclaw_snapshot(), indent=2) + "\n"
    bad = [(p, m.group(0)[:20]) for p, text in outputs.items() for m in SECRETISH.finditer(text)]
    if bad:
        print("refusing to write: secret-like or machine-specific content found:", bad, file=sys.stderr)
        return 1
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
